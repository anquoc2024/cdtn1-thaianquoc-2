#!/usr/bin/env bash
# ============================================================
# Gọi MỌI endpoint API trên gói Docker đang chạy và lưu request + response THẬT vào
#   docs/api-examples.md   (dữ liệu nguồn cho docs/api-docs.md – BT3, thành phần 6)
#
# Cách chạy (từ gốc repo, sau khi docker compose up -d và cả hai dịch vụ healthy):
#   bash docs/scripts/goi-api-docker.sh
# Script tạo / sửa / xóa vài bản ghi thử → chỉ chạy trên dữ liệu mẫu của Docker.
# Muốn trả dữ liệu về như ban đầu: docker compose down -v && docker compose up -d
# Token trong lệnh và phản hồi được che (<token_...>) để tệp kết quả không lộ secret.
# Đăng nhập API bị giới hạn 10 lần / 3 phút: chạy lại liên tục có thể gặp 429 – đợi 3 phút.
# ============================================================
set -u
BASE="${BASE:-http://localhost:${APP_PORT:-3000}}"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"; cd "$ROOT" || exit 1
OUT=docs/api-examples.md
BODY="$(mktemp)"; HEAD="$(mktemp)"; trap 'rm -f "$BODY" "$HEAD"' EXIT

command -v python3 >/dev/null || { echo "Cần python3 (sudo apt install -y python3)." >&2; exit 1; }
curl -fs "$BASE/api/health" >/dev/null || { echo "Không gọi được $BASE – chạy docker compose up -d trước." >&2; exit 1; }

rb()      { docker compose exec -T app bin/rails runner "$1" 2>/dev/null; }
json_id() { python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["data"]["id"])' "$BODY" 2>/dev/null; }
login()   { curl -s -X POST "$BASE/api/session" -H 'Content-Type: application/json' \
              -d "{\"email_address\":\"$1\",\"password\":\"Mekong@2026\"}" | sed -E 's/.*"token":"([^"]+)".*/\1/'; }

echo "Lấy mã bản ghi thật từ dữ liệu mẫu…"
read -r C_DEV C_OTHER PHONE SERIAL_TAKEN K K_USED P P2 W <<< "$(rb '
  d = Device.order(:id).first
  print d.customer_id, " ", Customer.where.not(id: d.customer_id).order(:id).first.id, " ",
        d.customer.phone, " ", d.serial_number, " ",
        IssueCategory.order(:id).first.id, " ", WarrantyRequest.order(:id).first.issue_category_id, " ",
        Priority.find_by!(name: "Cao").id, " ", Priority.find_by!(name: "Khẩn cấp").id, " ",
        WarrantyRequest.order(:id).first.id')"
[ -n "${W:-}" ] || { echo "Không đọc được dữ liệu mẫu (rails runner lỗi)." >&2; exit 1; }

NV="$(login quoc@mekong.vn)"; QL="$(login phu@mekong.vn)"
[ ${#NV} -ge 20 ] && [ ${#QL} -ge 20 ] || { echo "Đăng nhập API thất bại (có thể bị giới hạn 10 lần / 3 phút)." >&2; exit 1; }

{
  echo "# API examples — real requests and responses"
  echo
  echo "Generated by \`docs/scripts/goi-api-docker.sh\` on $(date '+%Y-%m-%d %H:%M:%S %z') against the Docker stack at $BASE"
  echo "(tag/commit \`$(git describe --tags --always 2>/dev/null)\`). Every request below was really sent and every response is copied"
  echo "unchanged, except that API tokens are replaced by \`<token_…>\`."
  echo
} > "$OUT"

N=0
call() {   # call "Tiêu đề" <tham số curl…>
  local title="$1"; shift; N=$((N + 1))
  local code shown loc
  code="$(curl -s -D "$HEAD" -o "$BODY" -w '%{http_code}' "$@")"
  shown="$(printf " '%s'" "$@")"; shown="${shown//$NV/<token_receptionist>}"; shown="${shown//$QL/<token_manager>}"
  {
    echo "## $N. $title"; echo
    echo '```bash'; echo "curl$shown"; echo '```'; echo
    echo "**HTTP $code**"
    loc="$(grep -i '^location:' "$HEAD" | tr -d '\r')"; [ -n "$loc" ] && { echo; echo "Response header: \`$loc\`"; }
    if [ -s "$BODY" ]; then
      echo; echo '```json'
      (python3 -m json.tool --no-ensure-ascii "$BODY" 2>/dev/null || cat "$BODY") | sed -E 's/("token": ")[^"]+"/\1<token>"/'
      echo '```'
    fi
    echo
  } >> "$OUT"
  printf '  %3s  %s\n' "$code" "$title"
}

J=(-H 'Content-Type: application/json')
A=(-H "Authorization: Bearer $NV")      # Nhân viên tiếp nhận
M=(-H "Authorization: Bearer $QL")      # Quản lý trung tâm
STAMP="$(date +%s)"; NEW_PHONE="09$(echo "$STAMP" | tail -c 9)"; SERIAL="SN-API-$STAMP"

echo "Đang gọi API…"
# ---------- Session & health ----------
call "POST /api/session — sign in (200)" -X POST "${J[@]}" -d '{"email_address":"quoc@mekong.vn","password":"Mekong@2026"}' "$BASE/api/session"
call "POST /api/session — wrong password (401)" -X POST "${J[@]}" -d '{"email_address":"quoc@mekong.vn","password":"sai-mat-khau"}' "$BASE/api/session"
call "GET /api/health — app and database up (200)" "$BASE/api/health"
call "GET /api/warranty_requests — no token (401)" "$BASE/api/warranty_requests"

# ---------- Customers ----------
call "GET /api/customers?q= — search by phone (200)" -G "${A[@]}" --data-urlencode "q=$PHONE" "$BASE/api/customers"
call "GET /api/customers?q= — invalid phone format (400)" -G "${A[@]}" --data-urlencode "q=0905 12" "$BASE/api/customers"
call "GET /api/customers/{id} — detail (200)" "${A[@]}" "$BASE/api/customers/$C_DEV"
call "POST /api/customers — create (201)" -X POST "${A[@]}" "${J[@]}" -d "{\"name\":\"Khách API\",\"phone\":\"$NEW_PHONE\",\"email\":\"khach.api@example.com\"}" "$BASE/api/customers"
NEW_C="$(json_id)"
call "POST /api/customers — duplicate phone (409)" -X POST "${A[@]}" "${J[@]}" -d "{\"name\":\"Trùng SĐT\",\"phone\":\"$NEW_PHONE\"}" "$BASE/api/customers"
call "POST /api/customers — invalid data (400)" -X POST "${A[@]}" "${J[@]}" -d '{"phone":"0905"}' "$BASE/api/customers"
call "POST /api/customers — manager not allowed (403)" -X POST "${M[@]}" "${J[@]}" -d '{"name":"Quản lý thử","phone":"0999000111"}' "$BASE/api/customers"
call "PATCH /api/customers/{id} — update (200)" -X PATCH "${A[@]}" "${J[@]}" -d '{"address":"1 Nguyễn Huệ, Quận 1"}' "$BASE/api/customers/$NEW_C"
call "DELETE /api/customers/{id} — delete (204)" -X DELETE "${A[@]}" "$BASE/api/customers/$NEW_C"
call "GET /api/customers/{id} — not found (404)" "${A[@]}" "$BASE/api/customers/$NEW_C"
call "DELETE /api/customers/{id} — customer has devices (409)" -X DELETE "${A[@]}" "$BASE/api/customers/$C_DEV"

# ---------- Issue categories ----------
call "GET /api/issue_categories — list (200)" "${A[@]}" "$BASE/api/issue_categories"
call "GET /api/issue_categories/{id} — detail (200)" "${A[@]}" "$BASE/api/issue_categories/$K"
call "POST /api/issue_categories — create (201)" -X POST "${A[@]}" "${J[@]}" -d "{\"name\":\"Nhóm thử API $STAMP\",\"description\":\"Tạo bởi script\"}" "$BASE/api/issue_categories"
NEW_K="$(json_id)"
call "POST /api/issue_categories — duplicate name (409)" -X POST "${A[@]}" "${J[@]}" -d "{\"name\":\"Nhóm thử API $STAMP\"}" "$BASE/api/issue_categories"
call "PATCH /api/issue_categories/{id} — update (200)" -X PATCH "${A[@]}" "${J[@]}" -d '{"description":"Đã sửa mô tả"}' "$BASE/api/issue_categories/$NEW_K"
call "DELETE /api/issue_categories/{id} — delete (204)" -X DELETE "${A[@]}" "$BASE/api/issue_categories/$NEW_K"
call "DELETE /api/issue_categories/{id} — category in use (409)" -X DELETE "${A[@]}" "$BASE/api/issue_categories/$K_USED"

# ---------- Lookups ----------
call "GET /api/priorities — priority levels and SLA (200)" "${A[@]}" "$BASE/api/priorities"
call "GET /api/stats — dashboard figures (200)" "${A[@]}" "$BASE/api/stats"

# ---------- Warranty requests ----------
call "GET /api/warranty_requests — list, filter overdue (200)" -G "${A[@]}" --data-urlencode "status=overdue" --data-urlencode "sort=due_at" "$BASE/api/warranty_requests"
call "GET /api/warranty_requests/{id} — detail (200)" "${A[@]}" "$BASE/api/warranty_requests/$W"
call "GET /api/warranty_requests/{id} — not found (404)" "${A[@]}" "$BASE/api/warranty_requests/999999"
VALID="{\"customer_id\":$C_DEV,\"device_type\":\"Điện thoại\",\"brand\":\"Samsung\",\"model\":\"Galaxy S24\",\"serial_number\":\"$SERIAL\",\"purchase_date\":\"2026-05-01\",\"issue_description\":\"Màn hình chớp tắt\",\"issue_category_id\":$K,\"priority_id\":$P}"
call "POST /api/warranty_requests — create (201)" -X POST "${A[@]}" "${J[@]}" -d "$VALID" "$BASE/api/warranty_requests"
NEW_W="$(json_id)"
call "POST /api/warranty_requests — missing required fields (400)" -X POST "${A[@]}" "${J[@]}" -d "{\"customer_id\":$C_DEV}" "$BASE/api/warranty_requests"
call "POST /api/warranty_requests — customer not found (404)" -X POST "${A[@]}" "${J[@]}" -d "${VALID/\"customer_id\":$C_DEV/\"customer_id\":999999}" "$BASE/api/warranty_requests"
call "POST /api/warranty_requests — serial belongs to another customer (409)" -X POST "${A[@]}" "${J[@]}" -d "$(echo "$VALID" | sed -e "s/\"customer_id\":$C_DEV/\"customer_id\":$C_OTHER/" -e "s/$SERIAL/$SERIAL_TAKEN/")" "$BASE/api/warranty_requests"
call "POST /api/warranty_requests — malformed JSON (400)" -X POST "${A[@]}" "${J[@]}" -d '{"customer_id": 1, brand' "$BASE/api/warranty_requests"
call "PATCH /api/warranty_requests/{id} — update fields, due date recalculated (200)" -X PATCH "${A[@]}" "${J[@]}" -d "{\"priority_id\":$P2,\"issue_description\":\"Màn hình chớp tắt, máy nóng\"}" "$BASE/api/warranty_requests/$NEW_W"
call "PATCH /api/warranty_requests/{id} — invalid value (400)" -X PATCH "${A[@]}" "${J[@]}" -d '{"issue_description":""}' "$BASE/api/warranty_requests/$NEW_W"
call "PATCH /api/warranty_requests/{id} — manager not allowed (403)" -X PATCH "${M[@]}" "${J[@]}" -d '{"issue_description":"Sửa trộm"}' "$BASE/api/warranty_requests/$NEW_W"
call "PATCH /api/warranty_requests/{id}/status — skip a step to completed (422)" -X PATCH "${A[@]}" "${J[@]}" -d '{"status":"completed"}' "$BASE/api/warranty_requests/$NEW_W/status"
call "PATCH /api/warranty_requests/{id}/status — start processing (200)" -X PATCH "${A[@]}" "${J[@]}" -d '{"status":"in_progress"}' "$BASE/api/warranty_requests/$NEW_W/status"
call "PATCH /api/warranty_requests/{id}/status — missing status (400)" -X PATCH "${A[@]}" "${J[@]}" -d '{}' "$BASE/api/warranty_requests/$NEW_W/status"
call "PATCH /api/warranty_requests/{id}/status — cancel without reason (400)" -X PATCH "${A[@]}" "${J[@]}" -d '{"status":"cancelled"}' "$BASE/api/warranty_requests/$NEW_W/status"
call "PATCH /api/warranty_requests/{id}/status — cancel with reason (200)" -X PATCH "${A[@]}" "${J[@]}" -d '{"status":"cancelled","note":"Khách xin nhận lại máy"}' "$BASE/api/warranty_requests/$NEW_W/status"
call "PATCH /api/warranty_requests/{id}/status — request already closed (409)" -X PATCH "${A[@]}" "${J[@]}" -d '{"status":"in_progress"}' "$BASE/api/warranty_requests/$NEW_W/status"
call "DELETE /api/warranty_requests/{id} — manager not allowed (403)" -X DELETE "${M[@]}" "$BASE/api/warranty_requests/$NEW_W"
call "DELETE /api/warranty_requests/{id} — delete (204)" -X DELETE "${A[@]}" "$BASE/api/warranty_requests/$NEW_W"
call "DELETE /api/warranty_requests/{id} — already deleted (404)" -X DELETE "${A[@]}" "$BASE/api/warranty_requests/$NEW_W"

# ---------- Sign out ----------
call "DELETE /api/session — sign out (204)" -X DELETE "${A[@]}" "$BASE/api/session"
call "GET /api/stats — old token after sign out (401)" "${A[@]}" "$BASE/api/stats"

echo; echo "Đã lưu $N request vào $OUT"
