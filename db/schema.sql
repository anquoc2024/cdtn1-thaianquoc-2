-- 1. NGUOI DUNG
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    encrypted_password VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_users_role
        CHECK (role IN ('receptionist', 'manager'))
);

-- 2. KHACH HANG
CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(20) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Index ho tro tra cuu khach hang bang so dien thoai
CREATE INDEX idx_customers_phone
    ON customers(phone);

-- 3. THIET BI
CREATE TABLE devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    serial_number VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_devices_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(id)
        ON DELETE RESTRICT
);

CREATE INDEX idx_devices_customer_id
    ON devices(customer_id);

-- 4. NHOM SU CO
CREATE TABLE issue_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5. MUC UU TIEN
CREATE TABLE priorities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    sla_hours INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_priorities_sla_hours
        CHECK (sla_hours > 0)
);

-- 6. YEU CAU BAO HANH
CREATE TABLE warranty_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    device_id BIGINT NOT NULL,
    issue_category_id BIGINT NOT NULL,
    priority_id BIGINT NOT NULL,
    created_by_id BIGINT NOT NULL,
    issue_description TEXT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'new',
    due_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_requests_device
        FOREIGN KEY (device_id)
        REFERENCES devices(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_requests_issue_category
        FOREIGN KEY (issue_category_id)
        REFERENCES issue_categories(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_requests_priority
        FOREIGN KEY (priority_id)
        REFERENCES priorities(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_requests_created_by
        FOREIGN KEY (created_by_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_warranty_requests_status
        CHECK (
            status IN ('new', 'processing', 'completed', 'cancelled')
        )
);

-- Index ho tro quan ly danh sach yeu cau theo trang thai va han xu ly
CREATE INDEX idx_requests_status_due_at
    ON warranty_requests(status, due_at);

CREATE INDEX idx_requests_device_id
    ON warranty_requests(device_id);

CREATE INDEX idx_requests_issue_category_id
    ON warranty_requests(issue_category_id);

CREATE INDEX idx_requests_priority_id
    ON warranty_requests(priority_id);

CREATE INDEX idx_requests_created_by_id
    ON warranty_requests(created_by_id);
